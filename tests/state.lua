vim.opt.rtp:prepend(vim.fn.getcwd())
local plugin = require("debug_tools")
assert(plugin.get_state().profiler == nil)
assert(not package.loaded["debug_tools.profiler"])
local hook = debug.gethook()
plugin.get_state()
assert(debug.gethook() == hook)
plugin.profiler.start()
assert(plugin.get_state().profiler.running)
local state = plugin.get_state()
state.profiler.running = false
assert(plugin.get_state().profiler.running)
plugin.profiler.stop()
assert(plugin.get_state().profiler.running == false)
plugin.dispose()
assert(plugin.get_state().enabled == false)
print("Debug public state: cold reads, profiler transitions and snapshot ownership passed")
